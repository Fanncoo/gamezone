create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text unique,
  type text not null check (type in ('news','review','article')),
  category text not null default 'СТАТЬЯ',
  excerpt text not null default '',
  body text not null default '',
  symbol text not null default '🎮',
  color text not null default '#f04452',
  score numeric(3,1) check (score is null or (score >= 0 and score <= 10)),
  published boolean not null default false,
  likes integer not null default 0,
  published_at timestamptz,
  created_at timestamptz not null default now()
);
create table if not exists public.likes (
  user_id uuid not null references public.profiles(id) on delete cascade,
  article_id bigint not null references public.articles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, article_id)
);
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  article_id bigint not null references public.articles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 3000),
  created_at timestamptz not null default now()
);
create index if not exists articles_published_idx on public.articles (published, published_at desc);
create index if not exists comments_article_idx on public.comments (article_id, created_at desc);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, username)
  values (new.id, nullif(new.raw_user_meta_data ->> 'username',''))
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.articles enable row level security;
alter table public.likes enable row level security;
alter table public.comments enable row level security;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin');
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

drop policy if exists "Profiles are publicly readable" on public.profiles;
create policy "Profiles are publicly readable" on public.profiles for select using (true);
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles for update to authenticated
using (id = (select auth.uid()) or public.is_admin())
with check ((id = (select auth.uid()) and role = 'user') or public.is_admin());
drop policy if exists "Admins manage profiles" on public.profiles;
create policy "Admins manage profiles" on public.profiles for all to authenticated
using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Read published articles" on public.articles;
create policy "Read published articles" on public.articles for select using (published = true or public.is_admin());
drop policy if exists "Admins insert articles" on public.articles;
create policy "Admins insert articles" on public.articles for insert to authenticated with check (public.is_admin());
drop policy if exists "Admins update articles" on public.articles;
create policy "Admins update articles" on public.articles for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Admins delete articles" on public.articles;
create policy "Admins delete articles" on public.articles for delete to authenticated using (public.is_admin());

drop policy if exists "Read likes" on public.likes;
create policy "Read likes" on public.likes for select to authenticated using (user_id = (select auth.uid()) or public.is_admin());
drop policy if exists "Insert own likes" on public.likes;
create policy "Insert own likes" on public.likes for insert to authenticated with check (user_id = (select auth.uid()));
drop policy if exists "Delete own likes" on public.likes;
create policy "Delete own likes" on public.likes for delete to authenticated using (user_id = (select auth.uid()) or public.is_admin());

create or replace function public.sync_article_likes()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare target_id bigint;
begin
  if TG_OP = 'DELETE' then target_id := old.article_id; else target_id := new.article_id; end if;
  update public.articles set likes = (select count(*) from public.likes where article_id = target_id) where id = target_id;
  if TG_OP = 'DELETE' then return old; else return new; end if;
end;
$$;
drop trigger if exists likes_count_insert on public.likes;
create trigger likes_count_insert after insert on public.likes for each row execute procedure public.sync_article_likes();
drop trigger if exists likes_count_delete on public.likes;
create trigger likes_count_delete after delete on public.likes for each row execute procedure public.sync_article_likes();

drop policy if exists "Read comments" on public.comments;
create policy "Read comments" on public.comments for select using (true);
drop policy if exists "Create own comments" on public.comments;
create policy "Create own comments" on public.comments for insert to authenticated with check (user_id = (select auth.uid()));
drop policy if exists "Delete own comments or admin" on public.comments;
create policy "Delete own comments or admin" on public.comments for delete to authenticated using (user_id = (select auth.uid()) or public.is_admin());

